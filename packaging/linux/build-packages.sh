#!/usr/bin/env bash
# The two Linux packages of one version: sluice's rpm and deb, each holding the command and the window on one Java
# runtime cut by jlink. CI's linux-packages job runs it on a tag; packaging/linux/check-packages.sh runs it locally.
#
#   build-packages.sh <version>      from the repository's root, after `mvn package`
#
# NFPM names the nfpm binary (default: nfpm on the PATH). NFPM_RPM_KEY_FILE and NFPM_RPM_PASSPHRASE sign the rpm
# (packaging/nfpm.yaml); left empty, nfpm signs nothing.
#
# Writes target/sluice-all.jar, target/sluice-desktop-all.jar, target/runtime and target/sluice.rpm, sluice.deb.
set -euo pipefail

VERSION="${1:?usage: build-packages.sh <version>}"
NFPM="${NFPM:-nfpm}"
export SLUICE_VERSION="$VERSION"
export NFPM_RPM_KEY_FILE="${NFPM_RPM_KEY_FILE:-}"

shopt -s nullglob
jar() {
  local found=("$1"/target/sluice-"$1"-*-all.jar)
  [ ${#found[@]} -eq 1 ] || {
    echo "::error::expected one $1/target/sluice-$1-*-all.jar, found ${#found[@]}: run mvn clean package first" >&2
    exit 1
  }
  echo "${found[0]}"
}

mkdir -p target
cp "$(jar cli)" target/sluice-all.jar
cp "$(jar desktop)" target/sluice-desktop-all.jar
java -jar target/sluice-all.jar --version
# Tab completion, generated by the jar it completes, so it offers the verbs that jar has (packaging/nfpm.yaml).
java -jar target/sluice-all.jar completion > target/sluice.bash
bash -n target/sluice.bash

# jlink refuses to write over a runtime, and a stale one would keep modules a newer jar no longer names.
rm -rf target/runtime target/desktop-runtime

# One runtime for both: what jdeps sees either jar's classes name, less JavaFX, which is in the window's jar on the
# class path (a JDK that bundles JavaFX must not have jdeps name its modules). Added, what is reached by lookup alone:
# jdk.charsets (a non-UTF-8 locale), jdk.unsupported (JavaFX's Unsafe), jdk.crypto.ec (TLS to GitHub),
# jdk.accessibility (a screen reader), jdk.localedata, jdk.zipfs; and java.desktop, which JavaFX needs.
seen=$(for jar in target/sluice-all.jar target/sluice-desktop-all.jar; do
    jdeps --print-module-deps --ignore-missing-deps --multi-release 25 "$jar" | tail -1 | tr ',' '\n'
  done | grep -v '^javafx\.' | sort -u | paste -sd, -)
jlink --add-modules "${seen:+$seen,}java.desktop,jdk.unsupported,jdk.zipfs,jdk.charsets,jdk.crypto.ec,jdk.localedata,jdk.accessibility" \
  --strip-debug --no-header-files --no-man-pages --output target/runtime
target/runtime/bin/java -jar target/sluice-all.jar --version
# A window cannot open here: check-packages.sh starts one under xvfb.
target/runtime/bin/java --list-modules | grep -q '^java.desktop@' \
  || { echo "::error::the runtime lacks java.desktop"; exit 1; }

"$NFPM" package -f packaging/nfpm.yaml -p rpm -t target/sluice.rpm
"$NFPM" package -f packaging/nfpm.yaml -p deb -t target/sluice.deb
